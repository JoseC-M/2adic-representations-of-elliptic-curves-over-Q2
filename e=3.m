// Proposition 6.2. Semistability defect 3.
// A is Frobenius, X is the single inertia generator and T is descent.
// Matrices act on columns. B takes normal-form coordinates to candidate coordinates.

P<z> := PolynomialRing(Rationals());
C<r> := NumberField(z^2+3);
sigma := hom<C -> C | -r>;
zeta := (-1+r)/2;
assert sigma(zeta) eq zeta^2 and zeta^2+zeta+1 eq 0;
D<U,V> := PolynomialRing(C,2);
R<u1,u2> := quo<D | 4*U^2+8*V^2-1>;

// Normal form. Both Frobenius and t act by sigma on coefficients.
A := Matrix(R,2,2,[0, -2, 1, 0]);
X := Matrix(R,2,2,[zeta, 0, 0, zeta^2]);
T := Matrix(R,2,2,[1, 0, 0, 1]);
sigmaX := Matrix(R,2,2,[sigma(zeta),0,0,sigma(zeta^2)]);
assert X^3 eq T and X ne T and X*sigmaX eq T and A*sigmaX eq X*A;

print "Normal form: A, X, T", A, X, T;

// u1 and u2 are fixed by sigma.
// Thus sigma(B)=B for every basis matrix written below; the two
// semilinear identities reduce to Ac*B=B*A and Tc*B=B*T.

// First sign. Generic case.
Ac := Matrix(R,2,2,[0, -2, 1, 0]);
Xc := Matrix(R,2,2,[-1/2+u1*r, 2*u2*r, u2*r, -1/2-u1*r]);
Tc := Matrix(R,2,2,[1, 0, 0, 1]);
Bgen := Matrix(R,2,2,[u1+1/2, -2*u2, u2, u1+1/2]);
assert Ac*Bgen eq Bgen*A;
assert Xc*Bgen eq Bgen*X;
assert Tc*Bgen eq Bgen*T;
print "Ac, Xc, Tc, Bgen", Ac, Xc, Tc, Bgen;
assert Determinant(Xc) eq 1;
assert Determinant(Bgen) eq u1+1/2;
// On the parameter conic u1=-1/2 forces u2=0.
X1 := Xc;

// First sign, singular case (u1,u2)=(-1/2,0).
Ac := Matrix(R,2,2,[0, -2, 1, 0]);
Xc := Matrix(R,2,2,[zeta^2, 0, 0, zeta]);
Tc := Matrix(R,2,2,[1, 0, 0, 1]);
Bsing := Matrix(R,2,2,[0, -2, 1, 0]);
assert Ac*Bsing eq Bsing*A;
assert Xc*Bsing eq Bsing*X;
assert Tc*Bsing eq Bsing*T;
print "Ac, Xc, Tc, Bsing", Ac, Xc, Tc, Bsing;
assert Determinant(Bsing) eq 2;

// Other sign: replace u2 by -u2. Generic case.
Ac := Matrix(R,2,2,[0, -2, 1, 0]);
Xc := Matrix(R,2,2,[-1/2+u1*r, -2*u2*r, -u2*r, -1/2-u1*r]);
Tc := Matrix(R,2,2,[1, 0, 0, 1]);
Bgen := Matrix(R,2,2,[u1+1/2, 2*u2, -u2, u1+1/2]);
assert Ac*Bgen eq Bgen*A;
assert Xc*Bgen eq Bgen*X;
assert Tc*Bgen eq Bgen*T;
print "Ac, Xc, Tc, Bgen", Ac, Xc, Tc, Bgen;
assert Determinant(Xc) eq 1;
assert Determinant(Bgen) eq u1+1/2;

X2 := Xc;

// Other sign, singular case (u1,u2)=(-1/2,0).
Ac := Matrix(R,2,2,[0, -2, 1, 0]);
Xc := Matrix(R,2,2,[zeta^2, 0, 0, zeta]);
Tc := Matrix(R,2,2,[1, 0, 0, 1]);
Bsing := Matrix(R,2,2,[0, -2, 1, 0]);
assert Ac*Bsing eq Bsing*A;
assert Xc*Bsing eq Bsing*X;
assert Tc*Bsing eq Bsing*T;
print "Ac, Xc, Tc, Bsing", Ac, Xc, Tc, Bsing;
assert Determinant(Bsing) eq 2;

// A direct intertwiner for the two candidate matrices, invertible everywhere.
S := Matrix(R,2,2,[u1, -2*u2, u2, u1]);
assert X1*S eq S*X2 and Ac*S eq S*Ac;
assert Determinant(S) eq 1/4;

// Filtration. Write s^3=2, x(s)=zeta*s, t(s)=s.
PC<v> := PolynomialRing(C);
K<s> := NumberField(v^3-2);
Q<a,b,c> := PolynomialRing(K,3);
// A t-fixed affine slope beta=a+b*s+c*s^2 must satisfy x(beta)=zeta*beta.
beta := a+b*s+c*s^2;
xBeta := a+b*zeta*s+c*zeta^2*s^2;
assert xBeta-zeta*beta eq (1-zeta)*a+(zeta^2-zeta)*c*s^2;
assert 1-zeta ne 0 and zeta^2-zeta ne 0;
// Independence of 1,s,s^2 gives a=c=0, and beta*s^2=2*b is rational.
assert (b*s)*s^2 eq 2*b;
// The resulting lines are generated by (alpha,s^2) and (1,0).
X := Matrix(Q,2,2,[zeta,0,0,zeta^2]);
line := Matrix(Q,2,1,[a,s^2]);
xLine := Matrix(Q,2,1,[a,(zeta*s)^2]);
infinity := Matrix(Q,2,1,[1,0]);
assert X*xLine eq zeta*line and X*infinity eq zeta*infinity;

print "Proposition 6.2 verified.";
